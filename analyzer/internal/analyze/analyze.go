// Package analyze is the pipeline: git history → per-file metrics → layout →
// City document. It is shared by the CLI, the hosted worker and the GitHub
// Action so all three produce byte-identical output for the same commit.
package analyze

import (
	"context"
	"fmt"
	"math"
	"sort"
	"strings"
	"time"
	"unicode/utf8"

	"github.com/harshitaajoshi/codeskyline/analyzer/internal/gitlog"
	"github.com/harshitaajoshi/codeskyline/analyzer/internal/layout"
	"github.com/harshitaajoshi/codeskyline/analyzer/internal/metrics"
	"github.com/harshitaajoshi/codeskyline/analyzer/internal/model"
	"github.com/harshitaajoshi/codeskyline/analyzer/internal/repo"
)

// Options tune one run.
type Options struct {
	Name         string // display name, e.g. "facebook/react"
	URL          string
	Rev          string // commit to analyze; defaults to HEAD
	DiffBase     string // when set, City.Diff describes Rev relative to this ref's merge base
	MaxCommits   int    // cap on first-parent commits walked; 0 = all
	Keyframes    int    // max timeline keyframes; defaults to 256
	MaxFileBytes int64  // files larger than this are not read for counting
	RecentWindow int64  // seconds; defaults to 365 days
	Now          int64  // analysis timestamp; defaults to time.Now
	// Progress receives human-readable stage updates.
	Progress func(stage, detail string)
}

func (o *Options) defaults() {
	if o.Keyframes == 0 {
		o.Keyframes = 256
	}
	if o.MaxFileBytes == 0 {
		o.MaxFileBytes = 4 << 20
	}
	if o.RecentWindow == 0 {
		o.RecentWindow = 365 * 24 * 3600
	}
	if o.Now == 0 {
		o.Now = time.Now().Unix()
	}
	if o.Progress == nil {
		o.Progress = func(string, string) {}
	}
}

// activityHalfLife drives the timeline hotspot score: how quickly a burst of
// commits stops counting. Six months.
const activityHalfLife = 180 * 24 * 3600

// fileAgg accumulates history for one logical file across renames.
type fileAgg struct {
	id      int // walk order; remapped to File.ID at the end
	path    string
	deleted bool
	gen     bool // vendored/generated by path heuristics (final flags come later)

	commits, recent, bugFixes int
	added, deleted_           int64
	recentChurn               int
	created, last             int64
	running, maxLines         int
	binary                    bool
	authors                   map[int]float64 // author index → decayed weight
	alive                     bool
	dist                      string // district (top two path segments) while alive

	// timeline state
	sinceKF    int     // commits since the previous keyframe
	ema        float64 // decayed commit rate
	emaT       int64
	owner      int32
	ownerDirty bool
	lastEvent  [4]int32 // lines, activity, owner, fire at the last emitted event
	lastK      int32    // keyframe of the last emitted event, -1 if none
	lastEvIdx  int      // offset of that event in the events slice
	fileIdx    int      // index into the final files slice
}

// Run analyzes r and returns its City.
func Run(ctx context.Context, r *repo.Repo, opt Options) (*model.City, error) {
	opt.defaults()
	rev := opt.Rev
	if rev == "" {
		rev = "HEAD"
	}
	head, err := r.Resolve(ctx, rev)
	if err != nil {
		return nil, err
	}
	lastTime, err := commitTime(ctx, r, head)
	if err != nil {
		return nil, err
	}
	total, err := r.CountCommits(ctx, head)
	if err != nil {
		return nil, err
	}
	n := total
	truncated := false
	if opt.MaxCommits > 0 && n > opt.MaxCommits {
		n = opt.MaxCommits
		truncated = true
	}
	// Keyframes spread evenly over the walk, always including the last commit.
	K := opt.Keyframes
	if K > n {
		K = n
	}
	kfAt := make([]int, n) // commit index → keyframe index or -1
	for i := range kfAt {
		kfAt[i] = -1
	}
	for k := 0; k < K; k++ {
		idx := n - 1
		if K > 1 {
			idx = k * (n - 1) / (K - 1)
		}
		kfAt[idx] = k
	}
	recentSince := lastTime - opt.RecentWindow

	// --- Pass 1: history -------------------------------------------------
	opt.Progress("history", fmt.Sprintf("walking %d first-parent commits", n))
	var (
		aggs      []*fileAgg
		byPath    = map[string]*fileAgg{}
		authors   []model.Author
		authorIdx = map[string]int{}
		commits   int
		firstTime int64
		keyframes []model.Keyframe
		events    []int32

		pairs      = metrics.NewPairCounter()
		cur        = newInterval(0)
		intervals  []*interval
		dirFiles   = map[string]int{} // district → live files
		dirMax     = map[string]int{}
		dirSeen    = map[string]bool{} // announced as a new district
		dirGone    = map[string]bool{}
		dirTouched = map[string]bool{}
		dirEvents  []districtEvent
	)
	ensure := func(p string) *fileAgg {
		if a, ok := byPath[p]; ok {
			return a
		}
		g, v := metrics.Classify(p, nil, nil)
		a := &fileAgg{id: len(aggs), path: p, gen: g || v, authors: map[int]float64{}, owner: -1, lastK: -1}
		aggs = append(aggs, a)
		byPath[p] = a
		return a
	}
	author := func(c *gitlog.Commit) int {
		key := metrics.IdentityKey(c.Author, c.Email)
		if i, ok := authorIdx[key]; ok {
			return i
		}
		i := len(authors)
		authorIdx[key] = i
		authors = append(authors, model.Author{
			Name: c.Author, Email: c.Email, Login: metrics.GitHubLogin(c.Email),
			FirstSeen: c.Time, LastSeen: c.Time,
		})
		return i
	}

	snapshot := func(k int, c *gitlog.Commit, ai int) {
		keyframes = append(keyframes, model.Keyframe{Index: commits - 1, Time: c.Time, Hash: c.Hash, Subject: truncate(c.Subject, 120), Author: ai})
		// Close the interval and note districts that appeared or vanished.
		cur.k, cur.time = k, c.Time
		intervals = append(intervals, cur)
		for d := range dirTouched {
			if d == "" {
				continue
			}
			if !dirSeen[d] && dirFiles[d] >= 8 {
				dirSeen[d] = true
				dirEvents = append(dirEvents, districtEvent{k: k, kind: "new", dir: d, n: dirFiles[d]})
			}
			if dirSeen[d] && !dirGone[d] && dirFiles[d] == 0 && dirMax[d] >= 8 {
				dirGone[d] = true
				dirEvents = append(dirEvents, districtEvent{k: k, kind: "gone", dir: d, n: dirMax[d]})
			}
		}
		dirTouched = map[string]bool{}
		cur = newInterval(k + 1)
		// Hotspots ranked among files alive at this keyframe. Complexity is
		// not known historically, so size stands in for it.
		in := make([]metrics.HotspotInput, len(aggs))
		for i, a := range aggs {
			alive := !a.deleted && a.running > 0
			rate := a.ema * math.Pow(0.5, float64(c.Time-a.emaT)/activityHalfLife)
			in[i] = metrics.HotspotInput{
				RecentCommits: int(rate + 0.5), RecentChurn: int(rate * 40),
				Complexity: int(math.Sqrt(float64(a.running)) * 10),
				Commits:    a.commits, BugFixes: a.bugFixes,
				Eligible: alive && !a.binary && !a.gen,
			}
		}
		_, fire := metrics.ScoreHotspots(in)
		for i, a := range aggs {
			lines := int32(0)
			if !a.deleted && a.running > 0 {
				lines = int32(a.running)
			}
			act := int32(min(a.sinceKF, 255))
			a.sinceKF = 0
			if a.ownerDirty {
				a.owner = argmaxOwner(a.authors)
				a.ownerDirty = false
			}
			ev := [4]int32{lines, act, a.owner, int32(fire[i])}
			if a.lastK < 0 && lines == 0 && act == 0 {
				continue // not born yet
			}
			if a.lastK >= 0 && ev == a.lastEvent {
				continue
			}
			a.lastEvent, a.lastK, a.lastEvIdx = ev, int32(k), len(events)
			events = append(events, int32(a.id), int32(k), ev[0], ev[1], ev[2], ev[3])
		}
	}

	err = gitlog.Walk(ctx, r.Dir, gitlog.Options{Rev: head, MaxCommits: opt.MaxCommits}, func(c *gitlog.Commit) error {
		commits++
		if firstTime == 0 || c.Time < firstTime {
			firstTime = c.Time
		}
		if commits%5000 == 0 {
			opt.Progress("history", fmt.Sprintf("%d / %d commits", commits, n))
		}
		ai := author(c)
		au := &authors[ai]
		au.Commits++
		if c.Time < au.FirstSeen {
			au.FirstSeen = c.Time
		}
		if c.Time > au.LastSeen {
			au.LastSeen = c.Time
		}
		bug := metrics.IsBugFix(c.Subject, c.Body)
		recent := c.Time >= recentSince
		// Decay relative to first commit; shares are normalized per file so
		// the reference point cancels out and nothing can overflow.
		w := math.Exp2(float64(c.Time-firstTime) / metrics.KnowledgeHalfLife)
		cur.commits++
		cur.authors[ai] = true
		var touched []int // logical file ids changed together, for coupling

		for _, ch := range c.Changes {
			var a *fileAgg
			switch ch.Status {
			case 'R':
				a = byPath[ch.OldPath]
				if a == nil {
					a = ensure(ch.OldPath)
				}
				delete(byPath, ch.OldPath)
				if other, ok := byPath[ch.Path]; ok && other != a {
					other.deleted = true // overwritten by the rename
				}
				byPath[ch.Path] = a
				a.path = ch.Path
				g, v := metrics.Classify(ch.Path, nil, nil)
				a.gen = g || v
			default:
				a = ensure(ch.Path)
			}
			a.deleted = ch.Status == 'D'
			a.commits++
			a.sinceKF++
			// District population, for "new district" / "demolished" events.
			nd := district(a.path)
			if a.alive {
				dirFiles[a.dist]--
				dirTouched[a.dist] = true
			}
			a.alive = !a.deleted
			a.dist = nd
			if a.alive {
				dirFiles[nd]++
				if dirFiles[nd] > dirMax[nd] {
					dirMax[nd] = dirFiles[nd]
				}
			}
			dirTouched[nd] = true
			a.ema = a.ema*math.Pow(0.5, float64(c.Time-a.emaT)/activityHalfLife) + 1
			a.emaT = c.Time
			if a.created == 0 || c.Time < a.created {
				a.created = c.Time
			}
			if c.Time > a.last {
				a.last = c.Time
			}
			if bug {
				a.bugFixes++
			}
			if ch.Binary {
				a.binary = true
			} else {
				touched = append(touched, a.id)
				cur.added += ch.Added
				cur.deleted += ch.Deleted
				cur.files[a.id] = true
				cur.dirChurn[nd] += ch.Added + ch.Deleted
				a.added += int64(ch.Added)
				a.deleted_ += int64(ch.Deleted)
				a.running += ch.Added - ch.Deleted
				if a.running > a.maxLines {
					a.maxLines = a.running
				}
				au.Added += int64(ch.Added)
				au.Deleted += int64(ch.Deleted)
				if ch.Added > 0 || ch.Deleted > 0 {
					a.authors[ai] += w * (float64(ch.Added) + 0.5*float64(ch.Deleted))
					a.ownerDirty = true
				}
			}
			if recent {
				a.recent++
				a.recentChurn += ch.Added + ch.Deleted
			}
		}
		pairs.Add(touched)
		if k := kfAt[min(commits-1, n-1)]; k >= 0 {
			snapshot(k, c, ai)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}

	// --- Pass 2: files at HEAD ------------------------------------------
	opt.Progress("files", "listing tree")
	entries, err := r.ListTree(ctx, head)
	if err != nil {
		return nil, err
	}
	attrs, _ := r.CheckAttrs(ctx, head, paths(entries))

	type pending struct {
		agg *fileAgg
		ent *repo.Entry
	}
	var all []pending
	atHead := map[*fileAgg]bool{}
	for i := range entries {
		e := &entries[i]
		a := byPath[e.Path]
		if a == nil { // history truncated before this file appeared
			a = ensure(e.Path)
		}
		atHead[a] = true
		all = append(all, pending{a, e})
	}
	for _, a := range aggs {
		if !atHead[a] && a.commits > 0 {
			all = append(all, pending{a, nil})
		}
	}
	// Stable ids: by path, live files before deleted namesakes.
	sort.SliceStable(all, func(i, j int) bool {
		if all[i].agg.path != all[j].agg.path {
			return all[i].agg.path < all[j].agg.path
		}
		return all[i].ent != nil && all[j].ent == nil
	})

	files := make([]model.File, len(all))
	var toRead []string
	readIdx := map[string][]int{} // blob sha → file indices (identical blobs share a sha)
	for i, p := range all {
		a := p.agg
		a.fileIdx = i
		f := model.File{
			ID: i, Path: a.path, MaxLines: a.maxLines,
			Commits: a.commits, RecentCommits: a.recent, Added: a.added, Deleted: a.deleted_,
			Created: a.created, LastTouched: a.last, BugFixes: a.bugFixes, Binary: a.binary,
			Owners: toOwners(metrics.TopOwners(a.authors, 3)),
		}
		if p.ent == nil {
			f.Removed = true
			f.Generated, f.Vendored = metrics.Classify(a.path, nil, nil)
			f.Lang = "Deleted"
			files[i] = f
			continue
		}
		e := p.ent
		at := attrs[e.Path]
		f.Generated, f.Vendored = metrics.Classify(e.Path, at.Generated, at.Vendored)
		f.Size = e.Size
		if e.Size <= opt.MaxFileBytes {
			if _, seen := readIdx[e.SHA]; !seen {
				toRead = append(toRead, e.SHA)
			}
			readIdx[e.SHA] = append(readIdx[e.SHA], i)
		} else {
			f.Lang = "Text"
			f.Lines = max(a.running, 0)
			f.Code = f.Lines
		}
		files[i] = f
	}

	opt.Progress("files", fmt.Sprintf("counting %d files", len(toRead)))
	mismatches := 0
	err = r.CatBlobs(ctx, toRead, func(sha string, content []byte) error {
		loc := metrics.Count("", content) // language is per path below
		for _, i := range readIdx[sha] {
			f := &files[i]
			l := loc
			if !loc.Binary {
				l = metrics.Count(f.Path, content)
			}
			f.Lang, f.Lines, f.Code, f.Comment, f.Blank, f.Complexity = l.Lang, l.Lines, l.Code, l.Comment, l.Blank, l.Complexity
			if l.Binary {
				f.Binary = true
				f.Lang = "Binary"
			}
			if l.Generated || l.Minified {
				f.Generated = true
			}
			if f.Lines > f.MaxLines {
				f.MaxLines = f.Lines
			}
			if !truncated && !f.Binary {
				if a := byPath[f.Path]; a != nil && a.running != f.Lines {
					mismatches++
				}
			}
		}
		return nil
	})
	if err != nil {
		return nil, err
	}

	// --- Metrics ---------------------------------------------------------
	opt.Progress("metrics", "scoring hotspots")
	in := make([]metrics.HotspotInput, len(files))
	for i, f := range files {
		in[i] = metrics.HotspotInput{
			RecentCommits: f.RecentCommits, RecentChurn: recentChurn(byPath[f.Path]),
			Complexity: f.Complexity, Commits: f.Commits, BugFixes: f.BugFixes,
			Eligible: !f.Removed && !f.Generated && !f.Vendored && !f.Binary && f.Lines > 0,
		}
	}
	scores, fire := metrics.ScoreHotspots(in)
	for i := range files {
		files[i].Hotspot = math.Round(scores[i]*1000) / 1000
		files[i].Fire = fire[i]
	}

	// Make the final keyframe agree with HEAD: real line counts (matters
	// for truncated histories) and the complexity-aware fire levels.
	if K > 0 {
		lastK := int32(K - 1)
		for _, p := range all {
			a := p.agg
			f := &files[a.fileIdx]
			ev := [4]int32{int32(f.Lines), a.lastEvent[1], a.owner, int32(f.Fire)}
			if f.Removed {
				ev[0] = 0
			}
			if a.lastK == lastK {
				copy(events[a.lastEvIdx+2:a.lastEvIdx+6], ev[:])
			} else if a.lastK < 0 || ev != a.lastEvent {
				if a.lastK < 0 {
					ev[1] = 0
				}
				events = append(events, int32(a.id), lastK, ev[0], ev[1], ev[2], ev[3])
			}
		}
	}
	// Remap event file ids from walk order to final ids and sort by file, k.
	idOf := make([]int32, len(aggs))
	for _, a := range aggs {
		idOf[a.id] = int32(a.fileIdx)
	}
	for i := 0; i < len(events); i += 6 {
		events[i] = idOf[events[i]]
	}
	events = sortEvents(events)

	// --- Coupling, story, diff -------------------------------------------
	opt.Progress("metrics", "mining co-changes")
	minSupport := 3
	if commits > 2000 {
		minSupport = 4
	}
	eligibleAgg := func(id int) bool {
		f := files[aggs[id].fileIdx]
		return !f.Removed && !f.Generated && !f.Vendored && !f.Binary && f.Lines > 0
	}
	ranked := metrics.RankCouplings(pairs.Pairs(), func(id int) int { return aggs[id].commits }, eligibleAgg, minSupport, 0.35, 1500)
	couplings := make([]model.Coupling, len(ranked))
	for i, cp := range ranked {
		couplings[i] = model.Coupling{A: aggs[cp.A].fileIdx, B: aggs[cp.B].fileIdx, Support: cp.Support, Confidence: math.Round(cp.Confidence*100) / 100}
	}
	story := detectEvents(intervals, dirEvents, authors, lastTime, 18)

	var diff *model.Diff
	if opt.DiffBase != "" {
		base, err := r.Resolve(ctx, opt.DiffBase)
		if err != nil {
			return nil, fmt.Errorf("diff base: %w", err)
		}
		mb, err := r.MergeBase(ctx, base, head)
		if err != nil {
			return nil, err
		}
		entries, err := r.Diff(ctx, mb, head)
		if err != nil {
			return nil, err
		}
		live := map[string]int{}
		gone := map[string]int{}
		for i, f := range files {
			if f.Removed {
				gone[f.Path] = i
			} else {
				live[f.Path] = i
			}
		}
		diff = &model.Diff{Base: mb, Head: head}
		for _, e := range entries {
			if e.Binary {
				continue
			}
			idx, ok := live[e.Path]
			if !ok {
				idx, ok = gone[e.Path]
			}
			if !ok {
				continue
			}
			diff.Files = append(diff.Files, model.DiffFile{ID: idx, Status: statusWord(e.Status), Added: e.Added, Deleted: e.Deleted})
		}
	}

	// --- Layout ----------------------------------------------------------
	opt.Progress("layout", "placing districts")
	items := make([]layout.Item, len(files))
	for i, f := range files {
		lines := f.MaxLines
		if f.Generated || f.Vendored || f.Binary {
			lines = min(lines, 200) // keep lockfiles from eating a district
		}
		items[i] = layout.Item{Path: f.Path, Area: layout.FootprintArea(lines)}
	}
	lay := layout.Place(items)
	dirs := make([]model.Dir, len(lay.Dirs))
	dirIdx := map[string]int{}
	for i, d := range lay.Dirs {
		dirs[i] = model.Dir{ID: i, Path: d.Path, Parent: d.Parent, Depth: d.Depth, Files: d.Leaves, Rect: d.Rect}
		dirIdx[d.Path] = i
	}
	// Knowledge: who still knows each file, and how many could leave.
	staleBefore := lastTime - 365*24*3600
	subtree := make([][][]int, len(dirs)) // dir → owner sets of live files beneath it
	for i := range files {
		f := &files[i]
		f.Rect = lay.Rects[i]
		f.Dir = dirIdx[parentDir(f.Path)]
		// Someone "knows" a file if they wrote a meaningful share of it and
		// are still around. A file touched within the year is not a ghost
		// even if its big owners have left: whoever touched it has context.
		var knowers []int
		for _, o := range f.Owners {
			if o.Share >= 0.1 && authors[o.Author].LastSeen >= staleBefore {
				knowers = append(knowers, o.Author)
			}
		}
		f.Ghost = !f.Removed && !f.Generated && !f.Vendored && len(f.Owners) > 0 && len(knowers) == 0 && f.LastTouched < staleBefore
		for d := f.Dir; d >= 0; d = dirs[d].Parent {
			dirs[d].Lines += f.Lines
			if !f.Removed && !f.Generated && !f.Vendored && !f.Binary {
				subtree[d] = append(subtree[d], knowers)
			}
		}
	}
	for i := range dirs {
		dirs[i].Bus = metrics.TruckFactor(subtree[i])
	}

	// --- Stats -----------------------------------------------------------
	st := model.Stats{Dirs: len(dirs), Languages: map[string]int{}, LineMismatches: mismatches}
	for _, f := range files {
		if f.Removed {
			st.Removed++
			continue
		}
		st.Files++
		st.Lines += f.Lines
		st.Code += f.Code
		st.MaxLines = max(st.MaxLines, f.Lines)
		st.MaxCommits = max(st.MaxCommits, f.Commits)
		if f.Fire > 0 {
			st.Burning++
		}
		if !f.Binary && !f.Generated && !f.Vendored {
			st.Languages[f.Lang] += f.Lines
		}
	}

	return &model.City{
		Version: model.Version,
		Repo: model.Repo{
			Name: opt.Name, URL: opt.URL, Head: head, DefaultBranch: r.DefaultBranch(ctx),
			AnalyzedAt: opt.Now, Commits: commits, FirstCommit: firstTime, LastCommit: lastTime,
			Truncated: truncated,
		},
		Authors:   authors,
		Dirs:      dirs,
		Files:     files,
		Stats:     st,
		Timeline:  model.Timeline{Keyframes: keyframes, Events: events, Story: story},
		Couplings: couplings,
		Diff:      diff,
	}, nil
}

func statusWord(s byte) string {
	switch s {
	case 'A':
		return "added"
	case 'D':
		return "deleted"
	case 'R':
		return "renamed"
	case 'C':
		return "copied"
	}
	return "modified"
}

func commitTime(ctx context.Context, r *repo.Repo, rev string) (int64, error) {
	var t int64
	err := gitlog.Walk(ctx, r.Dir, gitlog.Options{Rev: rev, MaxCommits: 1}, func(c *gitlog.Commit) error {
		t = c.Time
		return nil
	})
	return t, err
}

func argmaxOwner(w map[int]float64) int32 {
	best, bestW := int32(-1), 0.0
	for a, x := range w {
		if x > bestW || (x == bestW && best >= 0 && int32(a) < best) {
			best, bestW = int32(a), x
		}
	}
	return best
}

// sortEvents orders 6-tuples by (file, k). Events arrive keyframe-major.
func sortEvents(ev []int32) []int32 {
	n := len(ev) / 6
	idx := make([]int, n)
	for i := range idx {
		idx[i] = i
	}
	sort.SliceStable(idx, func(a, b int) bool {
		ea, eb := ev[idx[a]*6:], ev[idx[b]*6:]
		if ea[0] != eb[0] {
			return ea[0] < eb[0]
		}
		return ea[1] < eb[1]
	})
	out := make([]int32, 0, len(ev))
	for _, i := range idx {
		out = append(out, ev[i*6:i*6+6]...)
	}
	return out
}

func truncate(s string, n int) string {
	if utf8.RuneCountInString(s) <= n {
		return s
	}
	r := []rune(s)
	return string(r[:n-1]) + "…"
}

