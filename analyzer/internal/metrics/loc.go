// Package metrics turns raw git and file data into the numbers a city is
// built from: line counts, complexity, churn, ownership and hotspots.
package metrics

import (
	"bytes"
	"path"
	"sync"

	"github.com/boyter/scc/v3/processor"
)

var sccOnce sync.Once

func initSCC() {
	processor.ProcessConstants()
	processor.Complexity = true // opt-in: scc skips complexity unless set
	processor.Generated = true
	processor.Minified = true
}

// LOC is the per-file result of counting.
type LOC struct {
	Lang       string
	Lines      int
	Code       int
	Comment    int
	Blank      int
	Complexity int
	Binary     bool
	Generated  bool // scc's content-based detection (e.g. "Code generated by")
	Minified   bool
}

// Count classifies and counts one file. Unknown languages are still counted
// as plain lines so every text file gets a height.
func Count(p string, content []byte) LOC {
	sccOnce.Do(initSCC)
	if IsBinary(content) {
		return LOC{Binary: true}
	}
	name := path.Base(p)
	possible, ext := processor.DetectLanguage(name)
	lang := processor.DetermineLanguage(name, "", possible, content)
	if lang == "" {
		n := CountLines(content)
		return LOC{Lang: "Text", Lines: n, Code: n}
	}
	processor.LoadLanguageFeature(lang)
	job := &processor.FileJob{
		Filename:  name,
		Extension: ext,
		Location:  p,
		Language:  lang,
		Content:   content,
		Bytes:     int64(len(content)),
	}
	processor.CountStats(job)
	return LOC{
		Lang:       lang,
		Lines:      int(job.Lines),
		Code:       int(job.Code),
		Comment:    int(job.Comment),
		Blank:      int(job.Blank),
		Complexity: int(job.Complexity),
		Generated:  job.Generated,
		Minified:   job.Minified,
	}
}

// IsBinary uses git's own rule: a NUL byte in the first 8000 bytes.
func IsBinary(content []byte) bool {
	n := len(content)
	if n > 8000 {
		n = 8000
	}
	return bytes.IndexByte(content[:n], 0) >= 0
}

// CountLines counts lines the way git --numstat does: every newline ends a
// line, and a trailing partial line still counts.
func CountLines(content []byte) int {
	if len(content) == 0 {
		return 0
	}
	n := bytes.Count(content, []byte{'\n'})
	if content[len(content)-1] != '\n' {
		n++
	}
	return n
}
